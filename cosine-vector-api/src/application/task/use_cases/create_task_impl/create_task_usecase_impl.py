"""
Create task use case implementation.
"""
import reactivex # You might need this if you use reactivex.from_ or other reactivex top-level functions
from reactivex import Observable # <--- THIS IS THE CORRECT IMPORT FOR REACTIVEX

from src.domain.task.use_cases.create_task_case import CreateTaskUseCase, CreateTaskCommand
from src.domain.task.repositories.task_repository import TaskRepository
from src.domain.task.models.entities.task import Task


class CreateTaskUseCaseImpl(CreateTaskUseCase):
    """
    Implementation of CreateTaskUseCase.
    """
    
    def __init__(self, repository: TaskRepository):
        """
        Initialize the use case with a task repository.
        
        Args:
            repository: Task repository for data persistence
        """
        self.repository = repository
    
    def execute(self, command: CreateTaskCommand) -> Observable[Task]:
        """
        Execute the create task use case.
        
        Args:
            command: Command with task creation data
            
        Returns:
            Observable[Task]: Observable that emits the created task
        """
        # Create task entity from command
        task = Task(
            id=None,  # Will be generated by repository
            title=command.title,
            description=command.description,
            is_completed=command.is_completed
        )
        
        # Delegate to repository
        return self.repository.create(task)
